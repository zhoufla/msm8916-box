package com.sp970.smsrelay;

/**
 * LTE EARFCN → 频段号（3GPP 36.101 DL 表，纯逻辑、离线单测覆盖）。
 *
 * 用途：4.4 没有公开的"当前频段"API，但高通 RIL 一般支持 getAllCellInfo()，
 * 从 CellIdentityLte 拿到 EARFCN 后用这张表反查驻留频段（B1/B3/B8/B38/B41…）。
 * 未收录/落在空档的 EARFCN 返回空串，不硬造。
 *
 * 注意：B35/B36/B37 的 DL EARFCN 段重叠（36350–36949），表里按先命中先返回；
 * B24 与 B25 段重叠且极罕见，不收录。
 */
public final class LteBand {

    private LteBand() {
    }

    /** {band, dlLow, dlHigh}，按 dlLow 升序。 */
    private static final int[][] TABLE = {
        {1, 0, 599}, {2, 600, 1199}, {3, 1200, 1949}, {4, 1950, 2399},
        {5, 2400, 2649}, {6, 2650, 2749}, {7, 2750, 3449}, {8, 3450, 3799},
        {9, 3800, 4099}, {10, 4150, 4749}, {11, 4750, 4949}, {12, 5010, 5179},
        {13, 5180, 5279}, {14, 5280, 5379}, {17, 5730, 5849}, {18, 5850, 5999},
        {19, 6000, 6049}, {20, 6150, 6449}, {21, 6450, 6599}, {22, 6600, 7399},
        {23, 7500, 7699}, {25, 8040, 8689}, {26, 8690, 9039}, {27, 9040, 9099},
        {28, 9210, 9659}, {29, 9660, 9769}, {30, 9770, 9869}, {31, 9870, 9919},
        {32, 9920, 10359},
        {33, 36000, 36199}, {34, 36200, 36349}, {35, 36350, 36949},
        {38, 36950, 37549}, {39, 37550, 37949}, {40, 37950, 38349},
        {41, 38350, 38649}, {42, 38650, 39649}, {43, 39650, 41589},
        {44, 41590, 43589}
    };

    /** EARFCN → "B3" 之类；未知/非法返回 ""。 */
    public static String fromEarfcn(int earfcn) {
        if (earfcn < 0) return "";
        for (int i = 0; i < TABLE.length; i++) {
            if (earfcn >= TABLE[i][1] && earfcn <= TABLE[i][2]) return "B" + TABLE[i][0];
        }
        return "";
    }
}
